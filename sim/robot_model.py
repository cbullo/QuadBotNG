"""Build the explicit QuadBot linkage and ideal differential from the CAD URDF.

Coordinates/assumptions: docs/physical-model.md. No hardware code is executed.
The generated MJCF is standalone and uses relative STL paths.
"""

import argparse
import json
import math
import os
from pathlib import Path
import xml.etree.ElementTree as ET

import mujoco
import numpy as np
import yaml


SIM_DIR = Path(__file__).resolve().parent
PARAMETERS = json.loads((SIM_DIR / "robot_parameters.json").read_text())
COLLISION_GEOMETRY = json.loads((SIM_DIR / "collision_geometry.json").read_text())
LEGS = PARAMETERS["legs"]
ROBOT_CONFIG = yaml.safe_load((SIM_DIR.parent / "src/odroid_controller/controller/config/robot_config.yaml").read_text())
LEG_LIMITS = {leg: {key: float(ROBOT_CONFIG["legs"][f"leg_{leg}"][key])
                    for key in ("min_gamma", "max_gamma", "min_z", "max_z")}
              for leg in LEGS}
for limits in LEG_LIMITS.values():
    for axis in ("gamma", "z"):
        low, high = limits[f"min_{axis}"], limits[f"max_{axis}"]
        if not math.isfinite(low) or not math.isfinite(high) or low >= high:
            raise ValueError(f"Invalid configured {axis} limits: {limits}")


def stand_angles(leg):
    """CAD pose at the configured extension-side gamma bound, with z=0."""
    p, limits = LEGS[leg], LEG_LIMITS[leg]
    gamma = limits["max_gamma" if p["gamma_sign"] > 0 else "min_gamma"]
    delta = gamma / p["gamma_sign"]
    if not 0 <= delta < math.pi / 2 or not limits["min_z"] <= 0 <= limits["max_z"]:
        raise ValueError(f"Configured limits cannot form an uncrossed standing pose: {leg}")
    return math.pi / 4 - delta / 2, math.pi / 4 + delta / 2, 0


def leg_matrix(leg):
    """Map CAD [main, crank, shoulder] to relative [theta, gamma, z]."""
    p = LEGS[leg]
    return np.array([
        [p["theta_sign"] / 2, p["theta_sign"] / 2, 0],
        [-p["gamma_sign"], p["gamma_sign"], 0],
        [0, 0, p["z_sign"]],
    ])


def motor_matrix(leg):
    """Rotor radians = B @ CAD radians, in I/O/Z order; tau_q = B.T tau_m."""
    p = LEGS[leg]
    c = p["z_gamma_dir"] * 4 / 3
    inverse_controller = np.array([[-1, -0.5, -c / 2],
                                   [-1, 0.5, c / 2],
                                   [0, 0, 1]])
    return np.diag(p["gear_ratio"]) @ inverse_controller @ leg_matrix(leg)


def active_joints(leg):
    cad = LEGS[leg]["cad"]
    return [f"shoulder_to_main_{cad}", f"shoulder_to_crank_{cad}",
            f"base_to_shoulder_{cad}"]


def numbers(values):
    return " ".join(format(float(v), ".12g") for v in values)


def build_xml(*, fixed_base=False, leg=None, meshdir="../meshes"):
    """Convert this repository's expanded URDF, adding closures/transmissions.

    This is intentionally not a general-purpose URDF importer. Unsupported
    geometry, joints, or nonzero inertial rotations fail rather than disappear.
    """
    selected = tuple(LEGS) if leg is None else (leg,)
    cad_names = {LEGS[name]["cad"] for name in selected}
    source = ET.parse(SIM_DIR / "urdf/quadbot.urdf").getroot()
    links = {link.get("name"): link for link in source.findall("link")}
    children = {}
    for joint in source.findall("joint"):
        child = joint.find("child").get("link")
        if child == "drives_1" or any(child.endswith(f"_{c}_1") for c in cad_names):
            children.setdefault(joint.find("parent").get("link"), []).append(joint)

    root = ET.Element("mujoco", model="QuadBotNG candidate physical model")
    root.append(ET.Comment("Generated by //sim:generate_model; see docs/physical-model.md"))
    ET.SubElement(root, "compiler", angle="radian", meshdir=meshdir,
                  inertiafromgeom="false", autolimits="true")
    option = ET.SubElement(root, "option", timestep="0.0005", integrator="implicitfast",
                           solver="Newton", iterations="100", tolerance="1e-10",
                           jacobian="dense", cone="elliptic")
    ET.SubElement(option, "flag", energy="enable")
    ET.SubElement(root, "statistic", center="0 0 0.2", extent="0.8")
    visual = ET.SubElement(root, "visual")
    ET.SubElement(visual, "global", offwidth="1200", offheight="900")
    defaults = ET.SubElement(root, "default")
    ET.SubElement(defaults, "joint", damping=str(PARAMETERS["joint_damping_nm_s_per_rad"]),
                  solreffriction="0.002 1", solimpfriction="0.9999 0.9999 0.001",
                  solreflimit="0.002 1", solimplimit="0.99 0.9999 0.001")
    ET.SubElement(defaults, "geom", friction="0.8 0.005 0.0001",
                  solref="0.006 1", solimp="0.95 0.99 0.001")
    # Floor=1, chassis=2, outer leg envelopes=4/8/16/32. Each leg has a
    # separate internal-contact bit (64/128/256/512), preserving narrow fork
    # clearances without thinning its floor/chassis/other-leg envelope.
    outer_bits = sum(4 << i for i in range(len(LEGS)))
    for name, group, contype, affinity, rgba in [
        ("visual", "2", "0", "0", "0.65 0.69 0.74 1"),
        ("collision", "3", "2", str(1 | outer_bits), "0.3 0.6 0.8 0.3"),
    ]:
        d = ET.SubElement(defaults, "default", {"class": name})
        ET.SubElement(d, "geom", group=group, contype=contype,
                      conaffinity=affinity, rgba=rgba,
                      **({"solref": "0.002 1"} if name == "collision" else {}))
    assets = ET.SubElement(root, "asset")
    ET.SubElement(assets, "texture", name="grid", type="2d", builtin="checker",
                  rgb1="0.16 0.19 0.23", rgb2="0.23 0.27 0.31", width="512", height="512")
    ET.SubElement(assets, "material", name="floor", texture="grid", texrepeat="8 8",
                  texuniform="true", reflectance="0.1")
    world = ET.SubElement(root, "worldbody")
    ET.SubElement(world, "light", pos="0 -1 2", dir="0 0 -1", directional="true")
    ET.SubElement(world, "geom", name="ground", type="plane", size="2 2 0.1",
                  material="floor", contype="1", conaffinity=str(2 | outer_bits), priority="1", condim="6")
    base = ET.SubElement(world, "body", name="base_link", pos="0 0 0.4" if fixed_base else "0 0 0.23")
    if not fixed_base:
        ET.SubElement(base, "freejoint", name="floating_base")
    bodies = {"base_link": base}
    mesh_names = set()

    def populate(body, name):
        link = links[name]
        inertial = link.find("inertial")
        origin = inertial.find("origin")
        if any(float(v) for v in origin.get("rpy", "0 0 0").split()):
            raise ValueError(f"Unsupported inertial rotation: {name}")
        inertia = dict(inertial.find("inertia").attrib)
        if name.startswith("arm_crank_"):
            # CAD export rounded Ixx to zero. Explicit, documented replacement.
            inertia["ixx"] = str(PARAMETERS["crank_ixx_kg_m2"])
        ET.SubElement(body, "inertial", pos=origin.get("xyz"),
                      mass=inertial.find("mass").get("value"),
                      fullinertia=" ".join(inertia[k] for k in
                                           ("ixx", "iyy", "izz", "ixy", "ixz", "iyz")))
        for kind in ("visual",):
            for index, geometry in enumerate(link.findall(kind)):
                mesh = geometry.find("geometry/mesh")
                if mesh is None:
                    raise ValueError(f"Expected CAD mesh: {name}")
                filename = Path(mesh.get("filename")).name
                mesh_name = Path(filename).stem
                if mesh_name not in mesh_names:
                    ET.SubElement(assets, "mesh", name=mesh_name, file=filename,
                                  scale=mesh.get("scale", "1 1 1"))
                    mesh_names.add(mesh_name)
                o = geometry.find("origin")
                ET.SubElement(body, "geom", {"name": f"{name}_{kind}_{index}",
                              "class": kind, "type": "mesh", "mesh": mesh_name,
                              "pos": o.get("xyz"), "euler": o.get("rpy")})
        part = name if name in ("base_link", "drives_1") else name.rsplit("_", 2)[0]
        mirror = -1 if any(f"_{cad}_" in name for cad in ("LF", "LB")) else 1
        leg_index = next((i for i, p in enumerate(LEGS.values()) if name.endswith(f"_{p['cad']}_1")), None)
        shapes = [("collision", shape, i) for i, shape in enumerate(COLLISION_GEOMETRY[part])]
        if leg_index is not None:
            shapes += [("self_collision", shape, i) for i, shape in
                       enumerate(COLLISION_GEOMETRY["within_leg"][part])]
        for kind, shape, index in shapes:
            attributes = {"name": f"{name}_{kind}_{index}", "class": "collision",
                          "type": shape["type"], "size": numbers(shape["size"])}
            if leg_index is not None:
                bit = (64 if kind == "self_collision" else 4) << leg_index
                affinity = bit if kind == "self_collision" else (1 | 2 | (outer_bits ^ bit))
                attributes.update(contype=str(bit), conaffinity=str(affinity))
                if kind == "self_collision":
                    attributes["rgba"] = "0.9 0.55 0.15 0.6"
            for key in ("pos", "fromto"):
                if key in shape:
                    values = list(shape[key])
                    for i in range(1, len(values), 3):
                        values[i] *= mirror
                    attributes[key] = numbers(values)
            ET.SubElement(body, "geom", attributes)
        for joint in children.get(name, []):
            child_name = joint.find("child").get("link")
            o = joint.find("origin")
            child = ET.SubElement(body, "body", name=child_name,
                                  pos=o.get("xyz"), euler=o.get("rpy"))
            bodies[child_name] = child
            if joint.get("type") == "continuous":
                # Output-side dry friction is lumped at independent hinges;
                # passive bearing losses are not counted again around the loop.
                role = joint.get("name").rsplit("_", 1)[0]
                hinge = ET.SubElement(child, "joint", name=joint.get("name"), type="hinge",
                              axis=joint.find("axis").get("xyz"),
                              frictionloss=str(PARAMETERS["joint_frictionloss_nm"][role]))
                if role == "base_to_shoulder":
                    leg = next(n for n in selected if joint.get("name").endswith("_" + LEGS[n]["cad"]))
                    bounds = sorted(LEG_LIMITS[leg][k] / LEGS[leg]["z_sign"] for k in ("min_z", "max_z"))
                    hinge.set("range", numbers(bounds))
            elif joint.get("type") != "fixed":
                raise ValueError(f"Unsupported joint: {joint.attrib}")
            populate(child, child_name)

    populate(base, "base_link")
    contact = ET.SubElement(root, "contact")
    for name in selected:
        cad = LEGS[name]["cad"]
        # Mechanical interfaces, not blanket per-leg exclusions. Explicit base
        # exclusions also keep the floating/suspended variants consistent.
        for first, second in [
            ("base_link", f"shoulder_{cad}_1"),
            ("drives_1", f"shoulder_{cad}_1"),
            (f"arm_main_{cad}_1", f"arm_crank_{cad}_1"),
            (f"arm_lower_{cad}_1", f"arm_link_{cad}_1"),
        ]:
            ET.SubElement(contact, "exclude", body1=first, body2=second)
    equality = ET.SubElement(root, "equality")
    tendons = ET.SubElement(root, "tendon")
    actuators = ET.SubElement(root, "actuator")
    sensors = ET.SubElement(root, "sensor")
    custom = ET.SubElement(root, "custom")
    for name in selected:
        p = LEGS[name]
        cad = p["cad"]
        # 120 mm parallel arms; 35 mm crank and lower-arm closure lever.
        ET.SubElement(bodies[f"arm_link_{cad}_1"], "site", name=f"closure_link_{name}",
                      pos="0 0 -0.12", size="0.002", group="4")
        ET.SubElement(bodies[f"arm_lower_{cad}_1"], "site", name=f"closure_lower_{name}",
                      pos="0.035 0 0", size="0.002", group="4")
        # On the physical parallelogram branch, both passive angles are
        # crank-main. Point closure alone also admits a crossed assembly and
        # becomes ill-conditioned near the folded stop: tiny position errors
        # can let a loaded linkage snap onto that other branch. These two
        # scalar relations encode the same planar mobility without that toggle.
        for role in ("main_to_lower", "crank_to_link"):
            name_constraint = f"four_bar_{name}_{role}"
            closure = ET.SubElement(tendons, "fixed", name=name_constraint)
            for joint, coef in ((f"{role}_{cad}", 1),
                                (f"shoulder_to_crank_{cad}", -1),
                                (f"shoulder_to_main_{cad}", 1)):
                ET.SubElement(closure, "joint", joint=joint, coef=str(coef))
            ET.SubElement(equality, "tendon", name=name_constraint,
                          tendon1=name_constraint, polycoef="0 0 0 0 0",
                          solref="0.002 1", solimp="0.9999 0.9999 0.001")
        gamma = ET.SubElement(tendons, "fixed", name=f"gamma_{name}", limited="true",
                              range=numbers([LEG_LIMITS[name]["min_gamma"], LEG_LIMITS[name]["max_gamma"]]),
                              solreflimit="0.002 1", solimplimit="0.99 0.9999 0.001")
        for joint, coef in zip(active_joints(name)[:2], [-p["gamma_sign"], p["gamma_sign"]]):
            ET.SubElement(gamma, "joint", joint=joint, coef=str(coef))
        for axis, row, board, channel in zip("IOZ", motor_matrix(name), p["boards"], p["channels"]):
            motor = f"motor_{name}{axis}"
            tendon = ET.SubElement(tendons, "fixed", name=motor,
                                   armature=str(PARAMETERS["rotor_inertia_kg_m2"]),
                                   damping=str(PARAMETERS["motor_damping_nm_s_per_rad"]))
            for joint, coef in zip(active_joints(name), row):
                if coef:
                    ET.SubElement(tendon, "joint", joint=joint, coef=numbers([coef]))
            limit = PARAMETERS["demo_motor_torque_limit_nm"]
            ET.SubElement(actuators, "motor", name=motor, tendon=motor, gear="1",
                          ctrlrange=numbers([-limit, limit]))
            ET.SubElement(sensors, "actuatorpos", name=f"{motor}_angle", actuator=motor)
            ET.SubElement(sensors, "actuatorvel", name=f"{motor}_velocity", actuator=motor)
            ET.SubElement(custom, "text", name=f"{motor}_board", data=f"{board}:{channel}")
    stance = [] if fixed_base else [0, 0, 0.23, 1, 0, 0, 0]
    for joint in world.iter("joint"):
        stance.append(math.pi / 4 if joint.get("name").startswith(
            ("shoulder_to_main_", "shoulder_to_crank_")) else 0)
    keyframes = ET.SubElement(root, "keyframe")
    ET.SubElement(keyframes, "key", name="stance", qpos=numbers(stance))
    angles = {}
    for leg in selected:
        main, crank, shoulder = stand_angles(leg)
        roles = {"base_to_shoulder": shoulder, "shoulder_to_main": main,
                 "shoulder_to_crank": crank, "main_to_lower": crank - main,
                 "crank_to_link": crank - main}
        angles.update({f"{role}_{LEGS[leg]['cad']}": value for role, value in roles.items()})
    extended = [] if fixed_base else [0, 0, 0.30, 1, 0, 0, 0]
    extended.extend(angles[joint.get("name")] for joint in world.iter("joint"))
    ET.SubElement(keyframes, "key", name="stand", qpos=numbers(extended))
    # Upright chassis resting on its belly, with bent legs swung upward.
    # Rotate both driven links together to preserve the four-bar closure.
    belly_height = max(shape["size"][2] - shape["pos"][2]
                       for shape in COLLISION_GEOMETRY["base_link"])
    initial = [] if fixed_base else [0, 0, belly_height, 1, 0, 0, 0]
    initial.extend(-3 * math.pi / 4 if joint.get("name").startswith(
        ("shoulder_to_main_", "shoulder_to_crank_")) else 0
        for joint in world.iter("joint"))
    ET.SubElement(keyframes, "key", name="init", qpos=numbers(initial))
    ET.indent(root, space="  ")
    return ET.tostring(root, encoding="unicode") + "\n"


def load_model(*, fixed_base=False, leg=None):
    return mujoco.MjModel.from_xml_string(build_xml(
        fixed_base=fixed_base, leg=leg, meshdir=str(SIM_DIR / "meshes")))


def set_pose(model, data, poses=None):
    """Reset onto the uncrossed parallelogram branch, without solver settling.

    poses maps host leg names to CAD [main, crank, shoulder] radians. The
    default rotates the CAD rectangle by 45 degrees into a bent stance.
    Absolute hardware encoder and homing offsets are NOT represented.
    """
    mujoco.mj_resetData(model, data)
    for name, p in LEGS.items():
        cad = p["cad"]
        if mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, active_joints(name)[0]) < 0:
            continue
        main, crank, shoulder = (poses or {}).get(name, (math.pi / 4, math.pi / 4, 0))
        values = [main, crank, shoulder, crank - main, crank - main]
        joints = active_joints(name) + [f"main_to_lower_{cad}", f"crank_to_link_{cad}"]
        for joint, value in zip(joints, values):
            data.qpos[model.joint(joint).qposadr[0]] = value
    mujoco.mj_forward(model, data)


def closure_errors(model, data):
    return {name: float(np.linalg.norm(data.site(f"closure_link_{name}").xpos -
                                       data.site(f"closure_lower_{name}").xpos))
            for name in LEGS
            if mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_SITE, f"closure_link_{name}") >= 0}


def configure_demo_servos(model, kp=0.8, kd=0.005):
    """Inspection only: finite-gain rotor PD with the motor torque limits.

    ctrl becomes target rotor radians. MuJoCo integrates the velocity feedback
    implicitly, avoiding an explicit sampled damper destabilizing light links.
    The generated MJCF and load_model() retain plain torque-driven motors.
    """
    model.actuator_forcelimited[:] = True
    model.actuator_forcerange[:] = model.actuator_ctrlrange
    model.actuator_ctrllimited[:] = False
    model.actuator_gaintype[:] = mujoco.mjtGain.mjGAIN_FIXED
    model.actuator_biastype[:] = mujoco.mjtBias.mjBIAS_AFFINE
    model.actuator_gainprm[:, 0] = kp
    model.actuator_biasprm[:, 1] = -kp
    model.actuator_biasprm[:, 2] = -kd


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="sim/mujoco/quadbot.xml")
    parser.add_argument("--fixed-base", action="store_true")
    parser.add_argument("--leg", choices=LEGS)
    args = parser.parse_args()
    if "BUILD_WORKING_DIRECTORY" in os.environ:
        os.chdir(os.environ["BUILD_WORKING_DIRECTORY"])
    output = Path(args.output).resolve()
    xml = build_xml(fixed_base=args.fixed_base, leg=args.leg,
                    meshdir=os.path.relpath(SIM_DIR / "meshes", output.parent))
    # Compile before replacing an output file.
    model = load_model(fixed_base=args.fixed_base, leg=args.leg)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(xml)
    print(f"Wrote {output}: {model.nu} motors, {model.neq} closure constraints, "
          f"mass {model.body_mass.sum():.6f} kg")


if __name__ == "__main__":
    main()
